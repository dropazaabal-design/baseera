const norm = (w) => normalizeArabic(w);

// One-word entries match tokens; multi-word entries match the normalized text.
export const LEXICON = Object.fromEntries(
  Object.entries(RAW).map(([k, list]) => {
    const words = new Set();
    const phrases = [];
    for (const w of list) {
      const n = norm(w);
      if (n.includes(' ')) phrases.push(n);
      else words.add(n);
    }
    return [k, { words, phrases }];
  }),
);

// The token and its forms without common one-letter prefixes and the article.
export function variants(token) {
  const t = norm(token);
  const out = new Set([t]);
  const peel = (w) => {
    if (w.startsWith('ال') && w.length > 3) out.add(w.slice(2));
    for (const p of ['و', 'ف', 'ب', 'ل', 'ك']) {
      if (w.startsWith(p) && w.length > 3) {
        const rest = w.slice(1);
        out.add(rest);
        if (rest.startsWith('ال') && rest.length > 3) out.add(rest.slice(2));
      }
    }
  };
  peel(t);
  for (const v of [...out]) if (v.startsWith('ل') && v.length > 3) out.add(`ا${v}`); // «للنوم» → «النوم»
  return [...out];
}

// Count of lexicon hits in a token list plus phrase hits in the text.
export function hits(kind, tokens, normalizedText) {
  const lex = LEXICON[kind];
  let n = 0;
  const found = [];
  for (const tok of tokens) {
    if (variants(tok).some((v) => lex.words.has(v))) {
      n++;
      found.push(tok);
    }
  }
  for (const p of lex.phrases) {
    if (` ${normalizedText} `.includes(` ${p} `) || normalizedText.includes(p)) {
      n++;
      found.push(p);
    }
  }
  return { n, found };
}

export const isStopword = (tok) => variants(tok).some((v) => LEXICON.stop.words.has(v));
export const isNumberWord = (tok) => variants(tok).some((v) => LEXICON.numberWords.words.has(v));
